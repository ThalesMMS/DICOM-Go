type psfCancelCheckContext struct {
	context.Context
	remaining int
	cancel    context.CancelFunc
}

func psfCancelAfterChecks(n int) context.Context {
	c, cancel := context.WithCancel(context.Background())
	return &psfCancelCheckContext{Context: c, remaining: n, cancel: cancel}
}
func (c *psfCancelCheckContext) Err() error {
	c.remaining--
	if c.remaining <= 0 {
		c.cancel()
	}
	return c.Context.Err()
}
func TestPSFCancelNoPartial(t *testing.T) {
	src := psfTestVolume([3]int{8, 8, 8}, make([]float32, 512))
	for i := range src.Data {
		src.Data[i] = 1
	}
	k := psfNeighborKernel(src.Dims)
	o := psfTestOptions()
	ctx, cancel := context.WithCancel(context.Background())
	cancel()
	for _, c := range []context.Context{ctx, psfCancelAfterChecks(20)} {
		r, e := RichardsonLucy(c, src, k, o)
		if !errors.Is(e, context.Canceled) || r.Restored != nil || r.Metadata.Derived {
			t.Fatalf("partial cancel: %+v %v", r, e)
		}
	}
	if v, e := ConvolvePSFContext(psfCancelAfterChecks(10), src, k, o); !errors.Is(e, context.Canceled) || v != nil {
		t.Fatalf("forward cancel: %v %v", v, e)
	}
	if _, e := RichardsonLucy(nil, src, k, o); !errors.Is(e, ErrPSFDeconvolutionInput) {
		t.Fatal(e)
	}
}
func TestPSFConcurrentIndependentResults(t *testing.T) {
	src := psfTestVolume([3]int{3, 3, 1}, []float32{1, 2, 3, 4, 5, 6, 7, 8, 9})
	k := psfTestVolume([3]int{1, 1, 1}, []float32{1})
	o := psfTestOptions()
	var wg sync.WaitGroup
	results := make([]PSFDeconvolutionResult, 4)
	errs := make([]error, 4)
	for i := range results {
		wg.Add(1)
		go func(i int) { defer wg.Done(); results[i], errs[i] = RichardsonLucy(context.Background(), src, k, o) }(i)
	}
	wg.Wait()
	for i, r := range results {
		if errs[i] != nil {
			t.Fatal(errs[i])
		}
		psfAssertClose(t, r.Restored.Data, src.Data, 1e-6)
	}
	results[0].Restored.Data[0] = 42
	results[0].Metadata.SourceReferences[0] = "mutated"
	if results[1].Restored.Data[0] != 1 || results[1].Metadata.SourceReferences[0] != "synthetic:source" || src.Data[0] != 1 {
		t.Fatal("shared results/input")
	}
}

// ITK fixtures are external, bounded, source-stamped and optional. Generating
// them does not run as part of the default suite; see the guide's matched-model
// requirements. This is not a claim that ITK's default boundary/initialization
// agrees with this finite-field model.
func TestPSFITKOracleOptIn(t *testing.T) {
	path := os.Getenv("DICOM_GO_PSF_ITK_ORACLE")
	if path == "" {
		t.Skip("external ITK oracle not configured")
	}
	f, e := os.Open(path)
	if e != nil {
		t.Fatal(e)
	}
	defer f.Close()
	st, e := f.Stat()
	if e != nil || st.Size() > 1<<20 {
		t.Fatal("oracle exceeds 1 MiB or unreadable")
	}
	var oracle struct {
		Producer, Version, SourceSHA256, Model string
		Cases                                  []struct {
			Name                    string
			Dims                    [3]int
			SpacingMM               [3]float64
			Observed, PSF, Expected []float32
			PSFDims                 [3]int
			Iterations              int
			Boundary                PSFBoundary
			Tolerance               float64
		}
	}
	dec := json.NewDecoder(f)
	dec.DisallowUnknownFields()
	if e = dec.Decode(&oracle); e != nil {
		t.Fatal(e)
	}
	if e = dec.Decode(new(any)); e != io.EOF {
		t.Fatal("oracle trailing data")
	}
	if _, e = hex.DecodeString(oracle.SourceSHA256); e != nil {
		t.Fatal("oracle source hash")
	}
	if oracle.Producer != "ITK" || oracle.Version == "" || len(oracle.SourceSHA256) != 64 || oracle.Model != "matched-known-PSF-Poisson" || len(oracle.Cases) < 2 || len(oracle.Cases) > 8 {
		t.Fatal("oracle provenance/profile")
	}
	seen2, seen3 := false, false
	for _, c := range oracle.Cases {
		if c.Tolerance <= 0 || c.Tolerance > 1e-2 || !psfFinite(c.Tolerance) {
			t.Fatal("oracle tolerance")
		}
		o := psfTestOptions()
		o.Iterations = c.Iterations
		o.Boundary = c.Boundary
		o.Limits.MaxIterations = 4096
		src := &Volume{Dims: c.Dims, SpacingMM: c.SpacingMM, Data: c.Observed}
		k := &Volume{Dims: c.PSFDims, SpacingMM: c.SpacingMM, Data: c.PSF}
		r, e := RichardsonLucy(context.Background(), src, k, o)
		if e != nil {
			t.Fatalf("%s: %v", c.Name, e)
		}
		psfAssertClose(t, r.Restored.Data, c.Expected, c.Tolerance)
		if c.Dims[2] == 1 {
			seen2 = true
		} else {
			seen3 = true
		}
	}
	if !seen2 || !seen3 {
		t.Fatal("oracle must cover 2D and 3D")
	}
}

func TestPSFDeltaDynamicRange(t *testing.T) {
	for _, tc := range []struct {
		name string
		dims [3]int
		data []float32
	}{
		{"causal", [3]int{3, 1, 1}, []float32{1e30, 1, 0}},
		{"2D-extreme", [3]int{2, 2, 1}, []float32{math.MaxFloat32, math.SmallestNonzeroFloat32, 1, 0}},
		{"3D-extreme", [3]int{2, 2, 2}, []float32{math.MaxFloat32, math.SmallestNonzeroFloat32, 1, 0, 1e30, 1e-30, 5, 0}},
	} {
		for _, boundary := range []PSFBoundary{PSFZeroBoundary, PSFCircularBoundary} {
			for _, iterations := range []int{1, 20, 128} {
				for _, epsilon := range []float64{0, .75} {
					src := psfTestVolume(tc.dims, tc.data)
					k := psfTestVolume([3]int{1, 1, 1}, []float32{1})
					o := psfTestOptions()
					o.Iterations = iterations
					o.Boundary = boundary
					o.Epsilon = epsilon
					r, e := RichardsonLucy(context.Background(), src, k, o)
					if e != nil {
						t.Fatalf("%s border%d iterations%d epsilon%g: %v", tc.name, boundary, iterations, epsilon, e)
					}
					// Positive float32 output rounding must retain both ordinary small values
					// beside huge ones and the smallest representable subnormal sample.
					for i, want := range tc.data {
						if math.Float32bits(r.Restored.Data[i]) != math.Float32bits(want) {
							t.Fatalf("%s sample%d: %g want %g (iterations%d epsilon%g)", tc.name, i, r.Restored.Data[i], want, iterations, epsilon)
						}
					}
					if !reflect.DeepEqual(src.Data, tc.data) || !psfFinite(r.FinalRMSE) || !psfFinite(r.FinalPoissonDeviance) {
						t.Fatal("source/residual contract")
					}
				}
			}
		}
	}
}
