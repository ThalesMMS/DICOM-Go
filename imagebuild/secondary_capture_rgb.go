// SecondaryCaptureRGBOptions describes one native RGB8 Secondary Capture
// instance. This display image carries no patient-space geometry or rescale.
type SecondaryCaptureRGBOptions struct {
	Common object.DerivedCommon
	// Instance and series UIDs are generated when empty. An empty study UID
	// inherits the source study, or is generated by Common.Apply.
	SOPInstanceUID, StudyInstanceUID, SeriesInstanceUID string
	SeriesNumber, InstanceNumber                        int
	SeriesDescription                                   string
	Derivation                                          derivation.Derivation
	ContentTime                                         time.Time
	// Background is mandatory and must be opaque. Alpha is composited in
	// 8-bit encoded component space. NRGBA uses
	// floor((c*a + background*(255-a))/255); RGBA preserves its premultiplied
	// component and adds floor(background*(255-a)/255), without an additional
	// unpremultiply/repremultiply rounding step. No implicit background, color
	// profile conversion or linearization occurs.
	Background *color.NRGBA
	// BurnedInAnnotation must explicitly be YES or NO; the builder cannot
	// determine whether a screenshot contains identifying annotations.
	BurnedInAnnotation string
	// ConversionType defaults to WSD (workstation). Other defined SC
	// conversion terms may be supplied for other kinds of captured images.
	ConversionType string
	// Device fields describe the capturing equipment, independently of Common.
	DeviceManufacturer, DeviceModelName, DeviceSoftwareVersions string
	// MaxPixels bounds the allocation before reading any pixels. Zero uses
	// 16 Mi pixels. Native Pixel Data must also fit its 32-bit value length.
	MaxPixels int64
}

// BuildSecondaryCaptureRGBContext builds a single-frame Secondary Capture
// Image Storage object in Explicit VR Little Endian, with interleaved RGB8
// (Planar Configuration 0) and an even-length OB Pixel Data value.
//
// frame must be *image.NRGBA (straight alpha) or *image.RGBA (premultiplied
// alpha). Nonzero bounds, subimages and padded row strides are supported;
// malformed layouts are rejected before allocation or pixel access. The
// caller must keep frame and options stable during this call. The returned
// file owns its pixels and references. Cancellation is checked at least
// every 4096 pixels, including within wide rows.
func BuildSecondaryCaptureRGBContext(ctx context.Context, frame image.Image, opts SecondaryCaptureRGBOptions) (*object.File, error) {
	if ctx == nil {
		ctx = context.Background()
	}
	if err := ctx.Err(); err != nil {
		return nil, err
	}
	layout, err := captureRGBLayout(frame, opts.MaxPixels)
	if err != nil {
		return nil, err
	}
	file, err := buildRGBCaptureFile(ctx, layout.width, layout.height, secondaryCaptureImageStorage, opts)
	if err != nil {
		return nil, err
	}
	size := layout.rgbBytes
	pixels := make([]byte, int(size+size%2))
	if err := layout.encode(ctx, *opts.Background, pixels); err != nil {
		return nil, err
	}
	file.Dataset.Put(derivedio.Raw(core.TagPixelData, core.VROB, pixels))
	return file, nil
}

type rgbCaptureLayout struct {
	width, height, stride int
	pix                   []byte
	premultiplied         bool
	rgbBytes              int64
}

func captureRGBLayout(frame image.Image, maxPixels int64) (rgbCaptureLayout, error) {
	var rect image.Rectangle
	var pix []byte
	var stride int
	premultiplied := false
	switch img := frame.(type) {
	case *image.NRGBA:
		if img == nil {
			return rgbCaptureLayout{}, fmt.Errorf("%w: nil NRGBA frame", ErrInvalid)
		}
		rect, pix, stride = img.Rect, img.Pix, img.Stride
	case *image.RGBA:
		if img == nil {
			return rgbCaptureLayout{}, fmt.Errorf("%w: nil RGBA frame", ErrInvalid)
		}
		rect, pix, stride, premultiplied = img.Rect, img.Pix, img.Stride, true
	default:
		return rgbCaptureLayout{}, fmt.Errorf("%w: RGB capture requires NRGBA or RGBA", ErrInvalid)
	}
	// Unsigned subtraction handles rectangles whose signed Dx or Dy would overflow.
	width, height := uint64(rect.Max.X)-uint64(rect.Min.X), uint64(rect.Max.Y)-uint64(rect.Min.Y)
	if rect.Max.X <= rect.Min.X || rect.Max.Y <= rect.Min.Y || width > math.MaxUint16 || height > math.MaxUint16 {
		return rgbCaptureLayout{}, fmt.Errorf("%w: RGB capture dimensions", ErrInvalid)
	}
	rgbBytes, err := rgbCaptureLength(int(width), int(height), maxPixels)
	if err != nil {
		return rgbCaptureLayout{}, err
	}
	rowBytes := int(width) * 4
	if stride < rowBytes || len(pix) < rowBytes || height-1 > uint64((len(pix)-rowBytes)/stride) {
		return rgbCaptureLayout{}, fmt.Errorf("%w: RGB capture stride or buffer", ErrInvalid)
	}
	return rgbCaptureLayout{width: int(width), height: int(height), stride: stride, pix: pix, premultiplied: premultiplied, rgbBytes: rgbBytes}, nil
}

func rgbCaptureLength(width, height int, maxPixels int64) (int64, error) {
	if width <= 0 || height <= 0 || width > math.MaxUint16 || height > math.MaxUint16 {
		return 0, fmt.Errorf("%w: RGB capture dimensions", ErrInvalid)
	}
	if maxPixels == 0 {
		maxPixels = 16 << 20
	}
	count := int64(width) * int64(height)
	byteCount := count * 3
	padded := byteCount + byteCount%2
	if count > maxPixels || padded > math.MaxUint32-1 || uint64(padded) > uint64(^uint(0)>>1) {
		return 0, fmt.Errorf("%w: RGB capture pixel limit", ErrInvalid)
	}
	return byteCount, nil
}

func (layout rgbCaptureLayout) encode(ctx context.Context, background color.NRGBA, pixels []byte) error {
	rowBytes := layout.width * 4
	out := 0
	for y := 0; y < layout.height; y++ {
		row := layout.pix[y*layout.stride : y*layout.stride+rowBytes]
		for x := 0; x < rowBytes; x += 4 {
			if (out/3)%4096 == 0 {
				if err := ctx.Err(); err != nil {
					return err
				}
			}
			c := color.NRGBA{R: row[x], G: row[x+1], B: row[x+2], A: row[x+3]}
			if layout.premultiplied && (c.R > c.A || c.G > c.A || c.B > c.A) {
				return fmt.Errorf("%w: invalid premultiplied RGB pixel", ErrInvalid)
			}
			a, inverse := uint32(c.A), uint32(255-c.A)
			if layout.premultiplied {
				// c <= a, so each sum is <= a + (255-a) <= 255.
				pixels[out] = byte(uint32(c.R) + uint32(background.R)*inverse/255)
				pixels[out+1] = byte(uint32(c.G) + uint32(background.G)*inverse/255)
				pixels[out+2] = byte(uint32(c.B) + uint32(background.B)*inverse/255)
			} else {
				pixels[out] = byte((uint32(c.R)*a + uint32(background.R)*inverse) / 255)
				pixels[out+1] = byte((uint32(c.G)*a + uint32(background.G)*inverse) / 255)
				pixels[out+2] = byte((uint32(c.B)*a + uint32(background.B)*inverse) / 255)
			}
			out += 3
		}
	}
	return ctx.Err()
}

func buildRGBCaptureFile(ctx context.Context, width, height int, sopClass string, opts SecondaryCaptureRGBOptions) (*object.File, error) {
	if opts.Background == nil || opts.Background.A != 255 {
		return nil, fmt.Errorf("%w: an explicit opaque RGB background is required", ErrInvalid)
	}
	if opts.BurnedInAnnotation != "YES" && opts.BurnedInAnnotation != "NO" {
		return nil, fmt.Errorf("%w: explicit Burned In Annotation YES or NO is required", ErrInvalid)
	}
	conversion := opts.ConversionType
	if conversion == "" {
		conversion = "WSD"
	}
	switch conversion {
	case "DV", "DI", "DF", "WSD", "SD", "SI", "DRW", "SYN":
	default:
		return nil, fmt.Errorf("%w: SC conversion type", ErrInvalid)
	}
	for _, value := range []string{opts.SeriesDescription, opts.DeviceManufacturer, opts.DeviceModelName, opts.DeviceSoftwareVersions} {
		if !utf8.ValidString(value) || utf8.RuneCountInString(value) > 64 || strings.ContainsAny(value, "\\\x00") {
			return nil, fmt.Errorf("%w: SC equipment or description LO", ErrInvalid)
		}
	}
	if opts.SeriesNumber < 0 || int64(opts.SeriesNumber) > math.MaxInt32 || opts.InstanceNumber < 0 || int64(opts.InstanceNumber) > math.MaxInt32 || len(opts.Derivation.Sources) > 10000 || len(opts.Derivation.Codes) > 10000 {
		return nil, fmt.Errorf("%w: SC numbering or derivation limit", ErrInvalid)
	}
	var referencedFrames int
	for _, source := range opts.Derivation.Sources {
		if !core.IsValidUID(source.SOPClassUID) || !core.IsValidUID(source.SOPInstanceUID) || len(source.Frames) > 10000-referencedFrames {
			return nil, fmt.Errorf("%w: SC source reference", ErrInvalid)
		}
		referencedFrames += len(source.Frames)
	}
	sopUID, seriesUID := opts.SOPInstanceUID, opts.SeriesInstanceUID
	for _, uid := range []*string{&sopUID, &seriesUID} {
		if *uid == "" {
			var err error
			*uid, err = newUID()
			if err != nil {
				return nil, err
			}
		} else if !core.IsValidUID(*uid) {
			return nil, fmt.Errorf("%w: SC UID", ErrInvalid)
		}
	}
	if opts.StudyInstanceUID != "" && !core.IsValidUID(opts.StudyInstanceUID) {
		return nil, fmt.Errorf("%w: SC study UID", ErrInvalid)
	}
	now := opts.ContentTime
	if now.IsZero() {
		now = time.Now()
	}
	dataset := derivedio.Object(
		derivedio.UI(derivedio.TagSOPClassUID, sopClass), derivedio.UI(derivedio.TagSOPInstanceUID, sopUID),
		derivedio.UI(derivedio.TagSeriesInstanceUID, seriesUID), derivedio.CS(tagModality, "OT"),
		derivedio.Strings(tagImageType, core.VRCS, []string{"DERIVED", "SECONDARY"}), derivedio.CS(tagConversionType, conversion),
		derivedio.IS(tagSeriesNumber, opts.SeriesNumber), derivedio.IS(tagInstanceNumber, opts.InstanceNumber),
		derivedio.LO(tagSeriesDescription, opts.SeriesDescription), core.NewRawElement(tagPatientOrientation, core.VRCS, nil),
		object.DateElement(tagContentDate, now), object.TimeElement(tagContentTime, now),
		derivedio.US(derivedio.TagRows, uint16(height)), derivedio.US(derivedio.TagColumns, uint16(width)),
		derivedio.US(derivedio.TagSamplesPerPixel, 3), derivedio.CS(derivedio.TagPhotometricInterpretation, "RGB"),
		derivedio.US(core.NewTag(0x0028, 0x0006), 0), derivedio.US(derivedio.TagBitsAllocated, 8),
		derivedio.US(derivedio.TagBitsStored, 8), derivedio.US(derivedio.TagHighBit, 7), derivedio.US(derivedio.TagPixelRepresentation, 0),
		derivedio.CS(core.NewTag(0x0028, 0x0301), opts.BurnedInAnnotation), derivedio.CS(core.NewTag(0x0028, 0x2110), "00"),
	)
	if opts.StudyInstanceUID != "" {
		dataset.Put(derivedio.UI(tagStudyInstanceUID, opts.StudyInstanceUID))
	}
	for _, field := range []struct {
		tag   core.Tag
		value string
	}{
		{core.NewTag(0x0018, 0x1016), opts.DeviceManufacturer},
		{core.NewTag(0x0018, 0x1018), opts.DeviceModelName},
		{core.NewTag(0x0018, 0x1019), opts.DeviceSoftwareVersions},
	} {
		if field.value != "" {
			dataset.Put(derivedio.LO(field.tag, field.value))
		}
	}
	common := opts.Common
	common.Now = now
	if err := common.Apply(dataset, object.InheritWithoutFrameOfReference); err != nil {
		return nil, err
	}
	if err := derivation.Apply(dataset, opts.Derivation); err != nil {
		return nil, err
	}
	if err := ctx.Err(); err != nil {
		return nil, err
	}
	return derivedio.File(sopClass, sopUID, dataset)
}
