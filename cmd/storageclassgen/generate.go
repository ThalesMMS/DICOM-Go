package main

import (
	"bytes"
	"fmt"
	"go/format"
	"path/filepath"
	"strconv"
	"strings"
)

func generateSource(inputPath string, table Table) ([]byte, error) {
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by cmd/storageclassgen from %s (DICOM PS3.4 %s, extracted %s); DO NOT EDIT.\n\n", displaySourcePath(inputPath), table.Edition, table.Date)
	b.WriteString("package uid\n\n")
	fmt.Fprintf(&b, "// StorageCatalogEdition is the PS3.4 edition the Storage SOP Class catalog\n// was extracted from.\nconst StorageCatalogEdition = %q\n\n", table.Edition)
	b.WriteString("var storageSOPClasses = []StorageSOPClass{\n")
	for _, class := range table.Classes {
		fmt.Fprintf(&b, "\t{UID: %q, Name: %q, Keyword: %q, Category: %s, Modality: %q, Source: %q, Retired: %s},\n",
			class.UID, class.Name, class.Keyword, categoryConstants[class.Category], class.Modality, class.Source, strconv.FormatBool(class.Retired))
	}
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}

// displaySourcePath names the vendored TSV by its module path, so go generate
// (run from dictionary/uid with a relative -input) and a run from the module
// root write the same header.
func displaySourcePath(path string) string {
	clean := filepath.ToSlash(filepath.Clean(path))
	if strings.HasSuffix(clean, defaultInputPath) {
		return defaultInputPath
	}
	return clean
}
