// These two bindings have facts outside the dataset. Other conditions and
// clinical relationships remain unevaluated; no prose interpreter is added.
func externalFamily(table string, r ruleRow) string {
	if r.tag == "00081111" && r.typ == "1C" && r.condition == "Required if a Performed Procedure Step SOP Class was involved in the creation of this Series." {
		return "performed-procedure-step-participation"
	}
	if table == "General Contributing Sources Macro" && r.typ == "1C" && strings.HasPrefix(r.condition, "Required if present and consistent in the contributing SOP Instances.") {
		switch r.tag {
		case "00081090", "00181000", "00181020", "0008002A", "00081010", "00081070", "00081072", "00181030", "00400260", "00189423":
			return "contributing-sop-instance-consistency"
		}
	}
	return ""
}

// sourceTables selects precisely the legacy rule tables, with the same Include
// closure; generated sources cannot silently add or reinterpret a legacy row.
func sourceTables(b *book) map[string]string {
	out := map[string]string{}
	for _, id := range b.order {
		t := b.tables[id]
		if strings.HasSuffix(t.caption, " Module Attributes") || strings.HasSuffix(t.caption, " Macro Attributes") {
			name := b.tableName(id)
			if _, exists := out[name]; !exists {
				out[name] = id
			}
		}
	}
	for changed := true; changed; {
		changed = false
		for _, id := range b.order {
			name := b.tableName(id)
			if name == "" {
				continue
			}
			if _, exists := out[name]; exists {
				continue
			}
			added := false
			for _, selected := range out {
				for _, r := range b.rows(selected) {
					if r.include == name {
						out[name] = id
						changed = true
						added = true
						break
					}
				}
				if added {
					break
				}
			}
		}
	}
	return out
}

func sourceLinks(r row) []string {
	seen := map[string]bool{}
	var refs []string
	for _, c := range r.cells {
		for _, link := range c.links() {
			if link != "" && !seen[link] {
				seen[link] = true
				refs = append(refs, link)
			}
		}
	}
	return refs
}

func sourceEdition(b *book) string {
	fields := strings.Fields(strings.TrimPrefix(b.subtitle, "DICOM "))
	if len(fields) < 2 {
		return b.subtitle
	}
	return strings.Join(fields[:2], " ")
}

func sourceLiteral(b *book, t *table, ordinal, index int, depth int, tag, family string, refs []string) string {
	if tag == "" {
		tag = "0"
	} else {
		tag = "0x" + tag
	}
	var ref bytes.Buffer
	ref.WriteString("[]string{")
	for _, target := range refs {
		fmt.Fprintf(&ref, "%q,", target)
	}
	ref.WriteString("}")
	// Index disambiguates multiple projected Include links in one physical row.
	return fmt.Sprintf("RuleSource{Rule:%q,Source:ConstraintSource{Table:%q,TableID:%q,Row:%d,Index:%d,Depth:%d,Tag:%s,Section:%q,Edition:%q,SHA256:%q},CrossReferences:%s,ExternalFamily:%q}",
		fmt.Sprintf("%s/row-%d/index-%d", t.id, ordinal+1, index), b.tableName(t.id), t.id, ordinal+1, index, depth, tag, t.section, sourceEdition(b), b.digest, ref.String(), family)
}

func generateRuleSources(b *book) ([]byte, error) {
	var buf bytes.Buffer
	fmt.Fprintf(&buf, "// Code generated by cmd/iodmodulegen from the %s DocBook; DO NOT EDIT.\n\npackage iodmodules\n\n", b.subtitle)
	buf.WriteString("func init() {\nrowSources = map[string]map[int]RuleSource{\n")
	tables := sourceTables(b)
	names := make([]string, 0, len(tables))
	for name := range tables {
		names = append(names, name)
	}
	sort.Strings(names)
	for _, name := range names {
		t := b.tables[tables[name]]
		projected := b.rows(t.id)
		index := 0
		fmt.Fprintf(&buf, "%q:{\n", name)
		for ordinal, r := range t.rows {
			if len(r.cells) == 0 {
				continue
			}
			first := r.cells[0].text()
			count := 1
			if strings.HasPrefix(strings.TrimLeft(first, "> "), "Include") {
				count = 0
				for _, link := range r.cells[0].links() {
					if strings.HasPrefix(link, "table_") && b.tableName(link) != "" {
						count++
					}
				}
			} else if len(r.cells) < 3 {
				continue
			}
			for j := 0; j < count; j++ {
				if index >= len(projected) {
					return nil, fmt.Errorf("source projection count mismatch: %s", t.id)
				}
				row := projected[index]
				fmt.Fprintf(&buf, "%d:%s,\n", index, sourceLiteral(b, t, ordinal, index, row.depth, row.tag, externalFamily(name, row), sourceLinks(r)))
				index++
			}
		}
		if index != len(projected) {
			return nil, fmt.Errorf("source projection count mismatch: %s", t.id)
		}
		buf.WriteString("},\n")
	}
	buf.WriteString("}\n\nmoduleSources = map[string]map[int]RuleSource{\n")
	iods := map[string]*table{}
	for _, id := range b.order {
		t := b.tables[id]
		if !strings.HasSuffix(t.caption, " IOD Modules") {
			continue
		}
		for _, r := range t.rows {
			count := 0
			for _, c := range r.cells {
				if c.text() != "" {
					count++
				}
			}
			if count >= 2 {
				iods[strings.TrimSuffix(t.caption, " IOD Modules")] = t
				break
			}
		}
	}
	iodNames := make([]string, 0, len(iods))
	for name := range iods {
		iodNames = append(iodNames, name)
	}
	sort.Strings(iodNames)
	for _, name := range iodNames {
		t := iods[name]
		fmt.Fprintf(&buf, "%q:{\n", name)
		index := 0
		for ordinal, r := range t.rows {
			count := 0
			for _, c := range r.cells {
				if c.text() != "" {
					count++
				}
			}
			if count < 2 {
				continue
			}
			fmt.Fprintf(&buf, "%d:%s,\n", index, sourceLiteral(b, t, ordinal, index, 0, "", "", sourceLinks(r)))
			index++
		}
		buf.WriteString("},\n")
	}
	buf.WriteString("}\n}\n")
	return format.Source(buf.Bytes())
}
