package main

import (
	"bytes"
	"fmt"
	"go/format"
	"path/filepath"
	"strings"
	"unicode"
)

// namedSchemes get a package of named constants; every scheme is available
// through codes.Lookup.
var namedSchemes = []struct {
	designator, pkg, title string
}{
	{"DCM", "dcm", "DICOM Controlled Terminology (PS3.16 Annex D)"},
	{"SCT", "sct", "SNOMED CT concepts used in PS3.16"},
	{"UCUM", "ucum", "UCUM units used in PS3.16"},
	{"UMLS", "umls", "UMLS concepts used in PS3.16"},
	{"LN", "ln", "LOINC codes used in PS3.16"},
}

// generate returns the Go files of the named-constant packages under dir.
func generate(dir string, x Extraction) (map[string][]byte, error) {
	byScheme := map[string][]Term{"DCM": x.DCM}
	for _, term := range x.Others {
		byScheme[term.Scheme] = append(byScheme[term.Scheme], term)
	}
	files := map[string][]byte{}
	for _, scheme := range namedSchemes {
		source, err := generatePackage(scheme.designator, scheme.pkg, scheme.title, x, byScheme[scheme.designator])
		if err != nil {
			return nil, fmt.Errorf("%s: %w", scheme.pkg, err)
		}
		files[filepath.Join(dir, scheme.pkg, scheme.pkg+"_gen.go")] = source
	}
	return files, nil
}

func generatePackage(designator, pkg, title string, x Extraction, terms []Term) ([]byte, error) {
	names := identifiers(terms)
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by cmd/terminologygen from DICOM %s (part16.xml sha256 %s). DO NOT EDIT.\n\n", x.Edition, x.SHA256)
	fmt.Fprintf(&b, "// Package %s names the %s: each variable is the\n// coded concept with the Code Meaning PS3.16 gives it.\n", pkg, title)
	fmt.Fprintf(&b, "package %s\n\nimport \"github.com/ThalesMMS/dicom-go/codes\"\n\n", pkg)
	fmt.Fprintf(&b, "// Scheme is the Coding Scheme Designator of this package's codes.\nconst Scheme = %q\n\nvar (\n", designator)
	for i, term := range terms {
		fmt.Fprintf(&b, "\t// %s is (%s, %s, %q).\n", names[i], term.Value, designator, term.Meaning)
		if term.Retired {
			fmt.Fprintf(&b, "\t//\n\t// Deprecated: retired in PS3.16.\n")
		}
		fmt.Fprintf(&b, "\t%s = codes.Code{Value: %q, Scheme: Scheme, Meaning: %q}\n", names[i], term.Value, term.Meaning)
	}
	b.WriteString(")\n")
	return format.Source(b.Bytes())
}

// identifiers names each term after its Code Meaning. Names shared by
// several codes keep the plain name for the only current one, if any, and
// take the code value as a suffix otherwise.
func identifiers(terms []Term) []string {
	base := make([]string, len(terms))
	groups := map[string][]int{}
	for i, term := range terms {
		base[i] = camel(term.Meaning)
		if base[i] == "" {
			base[i] = "Code" + camel(term.Value)
		}
		groups[base[i]] = append(groups[base[i]], i)
	}
	names := make([]string, len(terms))
	for name, members := range groups {
		current := -1
		currentCount := 0
		for _, i := range members {
			if !terms[i].Retired {
				current, currentCount = i, currentCount+1
			}
		}
		for _, i := range members {
			if len(members) == 1 || currentCount == 1 && i == current {
				names[i] = name
				continue
			}
			names[i] = name + "_" + suffix(terms[i].Value)
		}
	}
	// A suffixed name can still meet another base name; number the rest.
	seen := map[string]int{}
	for i := range names {
		seen[names[i]]++
		if n := seen[names[i]]; n > 1 {
			names[i] = fmt.Sprintf("%s_%d", names[i], n)
		}
	}
	return names
}

var symbolWords = strings.NewReplacer(
	"%", " percent ", "/", " per ", "+", " plus ", "#", " number ", "&", " and ", "<", " less than ",
	">", " greater than ", "=", " equals ", "°", " degree ", "µ", "u", "μ", "u", "²", "2", "³", "3", "±", " plus minus ",
	"'", "", "’", "",
)

// camel turns a meaning into an exported Go identifier: its ASCII words
// capitalized and joined, with N before a leading digit.
func camel(meaning string) string {
	var b strings.Builder
	upper := true
	for _, r := range symbolWords.Replace(meaning) {
		switch {
		case r < unicode.MaxASCII && (unicode.IsLetter(r) || unicode.IsDigit(r)):
			if upper {
				r = unicode.ToUpper(r)
			}
			b.WriteRune(r)
			upper = false
		default:
			upper = true
		}
	}
	name := b.String()
	if name != "" && unicode.IsDigit(rune(name[0])) {
		name = "N" + name
	}
	return name
}

// suffix is a code value as an identifier suffix.
func suffix(value string) string {
	var b strings.Builder
	for _, r := range value {
		if r < unicode.MaxASCII && (unicode.IsLetter(r) || unicode.IsDigit(r)) {
			b.WriteRune(r)
		} else {
			b.WriteRune('_')
		}
	}
	return b.String()
}
