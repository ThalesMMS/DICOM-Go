package main

import (
	"bytes"
	"fmt"
	"go/format"
	"path/filepath"
	"strings"
)

// goTerm renders a normalized term as an sr relationshipTerm literal.
func goTerm(term string, valueTypes bool) string {
	quote := func(value string) string {
		if valueTypes {
			return fmt.Sprintf("ValueType(%q)", value)
		}
		return fmt.Sprintf("%q", value)
	}
	switch {
	case term == "*":
		return "relationshipTerm{any: true}"
	case strings.HasPrefix(term, "*-"):
		return fmt.Sprintf("relationshipTerm{any: true, except: %q}", strings.TrimPrefix(term, "*-"))
	}
	values := strings.Split(term, ",")
	for i, value := range values {
		values[i] = quote(value)
	}
	if valueTypes {
		return fmt.Sprintf("relationshipTerm{valueTypes: []ValueType{%s}}", strings.Join(values, ", "))
	}
	return fmt.Sprintf("relationshipTerm{relationships: []string{%s}}", strings.Join(values, ", "))
}

func generateSource(inputPath string, table Table) ([]byte, error) {
	var out bytes.Buffer
	fmt.Fprintf(&out, `// Code generated by cmd/srrelgen; DO NOT EDIT.
//
// Source file: %s
// Source origin: DICOM PS3.3 %s, Section A.35, Tables A.35.x-2

package sr

// RelationshipConstraintsEdition is the PS3.3 edition of the SR relationship
// content constraints.
const RelationshipConstraintsEdition = %q

var relationshipIODs = []relationshipIOD{
`, filepath.ToSlash(inputPath), table.Edition, table.Edition)
	for _, iod := range table.IODs {
		policy, list, _ := strings.Cut(iod.ByReference, ":")
		var byReference string
		if list != "" {
			quoted := strings.Split(list, ",")
			for i, relationship := range quoted {
				quoted[i] = fmt.Sprintf("%q", relationship)
			}
			byReference = fmt.Sprintf("[]string{%s}", strings.Join(quoted, ", "))
		} else {
			byReference = "nil"
		}
		fmt.Fprintf(&out, "\t{\n\t\tsopClassUID: %q,\n\t\tname: %q,\n\t\ttable: %q,\n\t\tbyReference: %q,\n\t\tbyReferenceRelationships: %s,\n\t\trules: []relationshipRule{\n",
			iod.SOPClassUID, iod.Name, iod.Table, policy, byReference)
		for _, rule := range iod.Rules {
			fmt.Fprintf(&out, "\t\t\t{sources: %s, relationship: %s, targets: %s},\n",
				goTerm(rule.Sources, true), goTerm(rule.Relationship, false), goTerm(rule.Targets, true))
		}
		out.WriteString("\t\t},\n\t},\n")
	}
	out.WriteString("}\n")
	return format.Source(out.Bytes())
}
