package main

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"fmt"
	"go/format"
	"path/filepath"
	"strings"
)

// generateSource turns the catalog into sr/template_catalog_gen.go. tsv is
// the TSV it was read from, whose SHA-256 becomes the definitions'
// provenance checksum. The source file is named relative to the module
// root, whether the generator runs from there or through go generate in sr/.
func generateSource(inputPath string, tsv []byte, c Catalog) ([]byte, error) {
	if err := check(c); err != nil {
		return nil, err
	}
	sum := sha256.Sum256(tsv)
	var out bytes.Buffer
	fmt.Fprintf(&out, `// Code generated by cmd/srtemplategen; DO NOT EDIT.
//
// Source file: %s
// Source origin: DICOM PS3.16 %s, Annex A template tables (%s)

package sr

import "github.com/ThalesMMS/dicom-go/codes"

const (
	// StandardTemplateEdition is the PS3.16 edition of the template
	// catalog, and the Version of its TemplateKeys.
	StandardTemplateEdition = %q
	// StandardTemplateSource is "part16.xml" when the catalog was
	// extracted from the PS3.16 DocBook and "curated" for a curated subset.
	StandardTemplateSource = %q
	// StandardTemplateSourceSHA256 is the SHA-256 of the extracted
	// part16.xml, "-" for a curated catalog.
	StandardTemplateSourceSHA256 = %q
	// StandardTemplateCatalogSHA256 is the SHA-256 of the catalog TSV, the
	// provenance checksum of the generated definitions.
	StandardTemplateCatalogSHA256 = %q
)

var _ = codes.Code{}

var standardTemplateCatalog = []catalogTemplate{
`, strings.TrimLeft(filepath.ToSlash(inputPath), "./"), c.Edition, c.Source, c.Edition, c.Source, c.SHA256, hex.EncodeToString(sum[:]))
	for _, t := range c.Templates {
		rows, err := interpret(t)
		if err != nil {
			return nil, fmt.Errorf("TID %s: %w", t.identifier(), err)
		}
		identity := fmt.Sprintf("id: %d", t.ID)
		if t.Identifier != "" {
			identity += fmt.Sprintf(", identifier: %q", t.Identifier)
		}
		fmt.Fprintf(&out, "\t{%s, name: %q, extensible: %t, order: %q, root: %q, rows: []catalogRow{\n",
			identity, t.Name, t.Type == "Extensible", t.Order, t.Root)
		for _, r := range rows {
			var fields []string
			add := func(format string, args ...any) { fields = append(fields, fmt.Sprintf(format, args...)) }
			add("label: %q", r.Label)
			if r.Level != 0 {
				add("level: %d", r.Level)
			}
			if r.Relationship != "" {
				add("relationship: %q", r.Relationship)
			}
			if r.ByReference {
				add("byReference: true")
			}
			if r.Include != 0 {
				add("include: %d", r.Include)
			} else if r.IncludeIdentifier != "" {
				add("includeIdentifier: %q", r.IncludeIdentifier)
			} else {
				add("valueType: %q", r.VT)
			}
			switch r.ConceptKind {
			case "EV", "DT":
				add("concept: %q, code: codes.Code{Value: %q, Scheme: %q, Meaning: %q}", r.ConceptKind, r.Code[0], r.Code[1], r.Code[2])
			case "CID":
				add("concept: %q, conceptCID: %d, conceptStrength: %q", r.ConceptKind, r.ConceptCID, r.ConceptStr)
			case "$":
				add("concept: %q, parameter: %q", r.ConceptKind, r.Parameter)
			}
			add("min: %d, max: %d, requirement: %q", r.Min, r.Max, r.Req)
			if r.Condition != "" {
				add("condition: %q", r.Condition)
			}
			if r.Row.Formal != "" {
				add("formal: %q", r.Row.Formal)
			}
			if r.Formal != nil {
				add("evaluate: %s", goCondition(r.Formal))
			}
			if r.ValueSet != "" {
				add("valueSet: %q", r.ValueSet)
			}
			if r.ValueSetCID != 0 {
				add("valueSetCID: %d, valueSetStrength: %q", r.ValueSetCID, r.ValueSetStr)
			}
			fmt.Fprintf(&out, "\t\t{%s},\n", strings.Join(fields, ", "))
		}
		out.WriteString("\t}},\n")
	}
	out.WriteString("}\n")
	return format.Source(out.Bytes())
}

func goCondition(c *condition) string {
	var args []string
	for _, arg := range c.Args {
		args = append(args, goCondition(arg))
	}
	rows := "nil"
	if len(c.Rows) > 0 {
		quoted := make([]string, len(c.Rows))
		for i, row := range c.Rows {
			quoted[i] = fmt.Sprintf("%q", row)
		}
		rows = "[]string{" + strings.Join(quoted, ", ") + "}"
	}
	if len(args) == 0 {
		return fmt.Sprintf("&catalogCondition{op: %q, rows: %s}", c.Op, rows)
	}
	return fmt.Sprintf("&catalogCondition{op: %q, args: []*catalogCondition{%s}}", c.Op, strings.Join(args, ", "))
}
